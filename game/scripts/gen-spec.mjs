// Builds src/spec/types.generated.ts and src/spec/validate.generated.js from
// ../schema/dungeon.schema.json. Run after changing the analyzer models.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import Ajv2020 from "ajv/dist/2020.js";
import standaloneCode from "ajv/dist/standalone/index.js";
import { compile } from "json-schema-to-typescript";

const here = (p) => fileURLToPath(new URL(p, import.meta.url));
const schema = JSON.parse(readFileSync(here("../../schema/dungeon.schema.json"), "utf8"));

const banner = "// Generated by scripts/gen-spec.mjs from schema/dungeon.schema.json. Do not edit.\n";

const types = await compile(schema, "DungeonSpec", {
  bannerComment: banner,
  additionalProperties: false,
  maxItems: -1,
  unreachableDefinitions: true,
  style: { semi: true, singleQuote: false },
});
writeFileSync(here("../src/spec/types.generated.ts"), types);

const ajv = new Ajv2020({ code: { source: true, esm: true }, allErrors: false, strict: false });
const validate = ajv.compile(schema);
// The standalone code still pulls one helper in with require(), which a
// browser bundle can't do. Inline it.
const ucs2length = `function ucs2length(str) {
  let length = 0;
  for (let pos = 0; pos < str.length; length++) {
    const c = str.charCodeAt(pos++);
    if (c >= 0xd800 && c <= 0xdbff && pos < str.length && (str.charCodeAt(pos) & 0xfc00) === 0xdc00) pos++;
  }
  return length;
}
`;
const code = standaloneCode(ajv, validate).replaceAll('require("ajv/dist/runtime/ucs2length").default', "ucs2length");
if (code.includes("require(")) throw new Error("validator still needs require()");
writeFileSync(here("../src/spec/validate.generated.js"), banner + "// @ts-nocheck\n" + ucs2length + code);
console.log("spec types and validator written");
